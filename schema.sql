-- Kingdom Fantasy Football (League ID: 1374816718416797696)
-- Supabase PostgreSQL Schema for Multi-User Salary Cap, Contracts & Automated ROS Rankings

create table if not exists public.league_settings (
  league_id text primary key default '1374816718416797696',
  league_name text not null default 'Kingdom Fantasy Football',
  salary_cap integer not null default 300,
  roster_size integer not null default 20,
  updated_at timestamptz not null default now()
);

create table if not exists public.contracts (
  id bigint generated by default as identity primary key,
  sleeper_player_id text,
  player_name text not null,
  position text not null,
  nfl_team text,
  roster_id integer not null,
  manager_handle text not null,
  salary integer not null default 1,
  years_remaining integer not null default 1,
  signed_year integer not null default 2026,
  expires_year integer not null default 2026,
  contract_type text not null default 'Active', -- 'Active', 'Rookie', 'Option', 'Taxi', 'IR'
  draft_slot text, -- e.g. '1.01' for Rookie Wage Scale option lookup
  option_salary integer, -- e.g. 28 for 1.01-1.03 (175% escalation)
  option_max_years integer, -- e.g. 3 for Round 1, 2 for 2.01-2.06, 1 for 2.07-2.12
  updated_at timestamptz not null default now(),
  unique(player_name, roster_id)
);

create table if not exists public.ros_rankings (
  player_name text primary key,
  position text not null,
  nfl_team text,
  ecr_overall integer not null,
  pos_rank text,
  ros_value numeric(6,2) not null,
  source_url text default 'https://www.fantasypros.com/nfl/rankings/ros-half-point-ppr-overall.php',
  updated_at timestamptz not null default now()
);

create table if not exists public.team_composite_scores (
  roster_id integer primary key,
  team_name text not null,
  manager_handle text not null,
  starter_score numeric(6,1) not null default 0,
  bench_score numeric(6,1) not null default 0,
  composite_score numeric(6,1) not null default 0,
  ros_rank integer not null default 1,
  updated_at timestamptz not null default now()
);

create table if not exists public.transactions_log (
  id bigint generated by default as identity primary key,
  action_type text not null, -- 'RELEASE', 'RFA_EXTENSION', 'ROOKIE_OPTION', 'TRADE', 'AUCTION_SIGN'
  roster_id integer not null,
  manager_handle text not null,
  player_name text not null,
  salary integer not null,
  dead_cap_penalty integer not null default 0,
  notes text,
  created_at timestamptz not null default now()
);

-- Enable Row Level Security (RLS)
alter table public.league_settings enable row level security;
alter table public.contracts enable row level security;
alter table public.ros_rankings enable row level security;
alter table public.team_composite_scores enable row level security;
alter table public.transactions_log enable row level security;

-- Public Read Policies for all League Managers
create policy "Allow public read on league_settings" on public.league_settings for select using (true);
create policy "Allow public read on contracts" on public.contracts for select using (true);
create policy "Allow public read on ros_rankings" on public.ros_rankings for select using (true);
create policy "Allow public read on team_composite_scores" on public.team_composite_scores for select using (true);
create policy "Allow public read on transactions_log" on public.transactions_log for select using (true);
